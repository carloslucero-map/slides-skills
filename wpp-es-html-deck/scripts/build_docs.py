#!/usr/bin/env python3
"""
build_docs.py — one source, two documents, one check.

The design guideline exists three times: references/sections/ (the source),
references/WPP-ES-DESIGN-GUIDELINE.md (all of it in one file) and
references/CORE.md (the always-loaded subset). Nothing kept them in step, and
the drift is silent because all three read plausibly on their own.

That is not hypothetical. The frame-constants commit edited CORE §2 and §12.15a
and left sections/ behind within the hour, in a repo whose own notes flag the
triplication as a standing hazard. Anyone can do it; nobody notices.

So: sections/ is the ONLY file anyone edits. This script emits the other two and
`--check` fails when either has drifted.

  python3 scripts/build_docs.py --write     # regenerate both
  python3 scripts/build_docs.py --check     # fail (exit 1) if either is stale

CORE is a SUBSET, selected by heading in the manifest below, and every CORE
heading must exist verbatim in sections/ — 47 of its 48 already did. The odd one
out is a wrapper CORE adds around the hoisted composition subsections, and it is
declared here rather than hidden in the text.

WHY THE MASTER IS ALSO GENERATED, when only CORE is loaded per deck: a --check
that covers CORE but not the master proves the wrong half. The next edit to a
section drifts the master instead, and the triplication returns wearing a gate.
The master goes to build/ (gitignored) with a stub left at the old path, because
it is the only single-file form a human reviewer or a diff against a future
playbook can use.
"""
import argparse, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
SKILL = os.path.dirname(HERE)
SECTIONS = os.path.join(SKILL, "references", "sections")
CORE_PATH = os.path.join(SKILL, "references", "CORE.md")
MASTER_PATH = os.path.join(SKILL, "build", "WPP-ES-DESIGN-GUIDELINE.md")

BANNER = ("<!-- GENERATED by scripts/build_docs.py from references/sections/. "
          "DO NOT EDIT — `build_docs.py --check` fails on drift and your edit "
          "is lost on the next --write. Edit the section file instead. -->\n\n")

