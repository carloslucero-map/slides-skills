def read_sections():
    """{heading: body} plus the ordered section files, from sections/*.md."""
    files = sorted(os.listdir(SECTIONS))
    files = [f for f in files if f.endswith(".md")]
    # _preamble sorts first by name already; keep numeric order for the rest.
    def key(f):
        m = re.match(r"(\d+)", f)
        return (0, 0, f) if f.startswith("_") else (1, int(m.group(1)) if m else 99, f)
    files.sort(key=key)

    blocks, whole = {}, []
    for f in files:
        text = open(os.path.join(SECTIONS, f), encoding="utf-8").read()
        whole.append(text.rstrip() + "\n")
        parts = re.split(r"^(#{2,3} .+)$", text, flags=re.M)
        for i in range(1, len(parts), 2):
            blocks[parts[i].strip()] = parts[i + 1].strip()
    return blocks, "\n".join(whole), files


def render_core(blocks):
    out = [BANNER, CORE_PREAMBLE]
    missing = []
    for entry in CORE_MANIFEST:
        if isinstance(entry, tuple):
            head, children = entry
            out.append(f"{head}\n\n{COMPOSITION_INTRO}\n")
            for c in children:
                if c not in blocks:
                    missing.append(c); continue
                out.append(f"{c}\n\n{blocks[c]}\n")
        else:
            if entry not in blocks:
                missing.append(entry); continue
            out.append(f"{entry}\n\n{blocks[entry]}\n")
    return "\n".join(out).rstrip() + "\n", missing


def render_master(whole):
    return BANNER + whole.rstrip() + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    if not (args.write or args.check):
        ap.error("pass --write or --check")

    blocks, whole, files = read_sections()
    core, missing = render_core(blocks)
    master = render_master(whole)

    if missing:
        print("MANIFEST ERROR — CORE asks for headings no section provides:", file=sys.stderr)
        for m in missing:
            print(f"  {m}", file=sys.stderr)
        sys.exit(1)

    targets = [(CORE_PATH, core), (MASTER_PATH, master)]

    if args.write:
        for path, text in targets:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            open(path, "w", encoding="utf-8").write(text)
            print(f"wrote {os.path.relpath(path, SKILL)} "
                  f"({len(text):,} chars, ~{len(text)*10//37:,} tokens)")
        print(f"from {len(files)} section files")
        return

    stale = []
    for path, text in targets:
        on_disk = open(path, encoding="utf-8").read() if os.path.isfile(path) else None
        if on_disk != text:
            stale.append((path, on_disk is None))
    if stale:
        print("DOCS STALE — sections/ has moved on and these have not:", file=sys.stderr)
        for path, absent in stale:
            print(f"  {os.path.relpath(path, SKILL)}"
                  f"{' (missing)' if absent else ''}", file=sys.stderr)
        print("\nRun: python3 scripts/build_docs.py --write", file=sys.stderr)
        print("If your edit was to CORE.md or the master, it is in the wrong "
              "file — move it into references/sections/ first.", file=sys.stderr)
        sys.exit(1)
    print(f"DOCS OK — CORE.md and the master both match references/sections/ "
          f"({len(files)} files)")


if __name__ == "__main__":
    main()
